"use client";

import { useTheme } from "next-themes";
import { Toaster as Sonner } from "sonner";

type ToasterProps = React.ComponentProps<typeof Sonner>;

const Toaster = ({ ...props }: ToasterProps) => {
  const { theme = "system" } = useTheme();

  return (
    <Sonner
      theme={theme as ToasterProps["theme"]}
      className="toaster group"
      // Bottom centre, above the phone's editing bar and keyboard; globals.css
      // moves it clear of a docked sidebar.
      position="bottom-center"
      mobileOffset={{
        bottom:
          "calc(var(--bottom-bar-height, 0px) + var(--keyboard-inset, 0px) + max(16px, env(safe-area-inset-bottom)))",
      }}
      toastOptions={{
        classNames: {
          toast:
            "group toast group-[.toaster]:bg-popover group-[.toaster]:text-foreground group-[.toaster]:border-border-subtle group-[.toaster]:shadow-[var(--elevation-overlay)]",
          description: "group-[.toast]:text-muted-foreground",
          actionButton:
            "group-[.toast]:bg-primary group-[.toast]:text-primary-foreground",
          cancelButton:
            "group-[.toast]:bg-muted group-[.toast]:text-muted-foreground",
        },
      }}
      {...props}
    />
  );
};

export { Toaster };
