const build = await Bun.build({
  entrypoints: [new URL("entry.ts", import.meta.url).pathname],
  target: "browser",
  format: "iife",
  minify: true,
});
if (!build.success || build.outputs.length !== 1)
  throw new Error("Native generation bundle unavailable");
const artifact = build.outputs[0];
if (!artifact) throw new Error("Missing native generation bundle");
const script = await artifact.text();
if (/\b(?:fetch|XMLHttpRequest|console|process|require)\b/.test(script))
  throw new Error("Unexpected native generation capability");
await Bun.write(
  new URL(
    "../Sources/LexidrawKit/NativeGenerationBundle.swift",
    import.meta.url,
  ),
  `// Generated by bun apps/ios/generation/build.ts.\nlet nativeGenerationScript = #"""\n${script}\n"""#\n`,
);
