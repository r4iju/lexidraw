import { fileURLToPath } from "node:url";
import {
  byCodeUnits,
  type FieldType,
  type NodeDescription,
  type NodeSchema,
} from "@packages/lexical-nodes/node-schema";

export const SERIALIZED_NODES_PATH = fileURLToPath(
  new URL("../Sources/LexicalSwift/SerializedNodes.swift", import.meta.url),
);

/**
 * Enum type names where a field's name doesn't give one: the field takes
 * different values on different nodes, or the name alone would be vague.
 * Keyed by the enum's non-null values.
 */
const ENUM_NAMES: Record<string, string> = {
  [enumSignature(["", "left", "start", "center", "right", "end", "justify"])]:
    "ElementFormat",
  [enumSignature(["normal", "token", "segmented"])]: "TextMode",
  [enumSignature(["normal"])]: "TabMode",
  [enumSignature(["h1", "h2", "h3", "h4", "h5", "h6"])]: "HeadingTag",
  [enumSignature(["ul", "ol"])]: "ListTag",
};

/** Names a payload's own members take, which no field may reuse. */
const RESERVED_MEMBERS = new Set(["children", "json", "type", "unknownFields"]);

const SWIFT_KEYWORDS = new Set(
  "associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self Self super throws true try".split(
    " ",
  ),
);

/** The Swift payload types for every declared node in `schema`. */
export function swiftForNodeSchema(schema: NodeSchema): string {
  const enums = enumNames(schema.nodes);
  const lines = [
    "// Generated by `bun run codegen` in apps/ios. Don't edit it.",
    "",
    ...serializedNode(schema.nodes),
    ...[...enums]
      .sort(([, a], [, b]) => byCodeUnits(a, b))
      .flatMap(([signature, name]) => enumeration(name, signature)),
    ...schema.nodes.flatMap((node) => payload(node, enums)),
  ];
  return `${lines.join("\n").trimEnd()}\n`;
}

function serializedNode(nodes: NodeDescription[]): string[] {
  const cases = nodes.map((node) => ({
    name: identifier(
      className(node).charAt(0).toLowerCase() + className(node).slice(1),
    ),
    payload: payloadName(node),
    type: node.type,
  }));
  if (cases.some(({ name }) => name === "opaque")) {
    throw new Error("A node class can't be called OpaqueNode");
  }
  return [
    "public enum SerializedNode: Equatable, Sendable {",
    ...cases.map(({ name, payload }) => `  case ${name}(${payload})`),
    "  /// A node whose type isn't declared, kept exactly as read.",
    "  case opaque(JSONValue)",
    "",
    "  public init(json: JSONValue) {",
    '    switch json["type"]?.stringValue {',
    ...cases.map(
      ({ name, type }) =>
        `    case ${swiftString(type)}: self.init(json, as: Self.${name})`,
    ),
    "    default: self = .opaque(json)",
    "    }",
    "  }",
    "",
    "  public var payload: (any NodePayload)? {",
    "    switch self {",
    ...cases.map(({ name }) => `    case .${name}(let node): node`),
    "    case .opaque: nil",
    "    }",
    "  }",
    "",
    "  public var json: JSONValue {",
    "    switch self {",
    ...cases.map(({ name }) => `    case .${name}(let node): node.json`),
    "    case .opaque(let json): json",
    "    }",
    "  }",
    "}",
    "",
  ];
}

function enumeration(name: string, signature: string): string[] {
  const cases = (JSON.parse(signature) as string[]).map((value) => {
    const member = caseName(value);
    return member === value
      ? `  case ${member}`
      : `  case ${member} = ${swiftString(value)}`;
  });
  return [
    `public enum ${name}: String, CaseIterable, Sendable, JSONEnumeration {`,
    ...cases,
    "}",
    "",
  ];
}

function payload(node: NodeDescription, enums: Map<string, string>): string[] {
  const fields = [
    ...Object.entries(node.fields),
    ...Object.entries(node.state).map(([key, state]) => {
      if (!state.flat) {
        throw new Error(
          `${node.type}: state "${key}" nests under "$", which codegen doesn't type yet`,
        );
      }
      return [key, state.value] as const;
    }),
  ]
    .sort(([a], [b]) => byCodeUnits(a, b))
    .map(([key, type]) => {
      if (RESERVED_MEMBERS.has(key)) {
        throw new Error(`${node.type}: a field can't be called ${key}`);
      }
      const field = swiftField(type, enums, `${node.type}.${key}`);
      return {
        key,
        name: identifier(key),
        ...field,
        property: field.nullable
          ? `Nullable<${field.value}>`
          : `${field.value}?`,
        schemaType: field.nullable ? `${field.value}?` : field.value,
        accessor: field.nullable ? "Nullable" : "",
      };
    });
  return [
    `public struct ${payloadName(node)}: ${node.children ? "ElementNodePayload" : "NodePayload"} {`,
    `  public static let type = ${swiftString(node.type)}`,
    ...(node.children ? ["  public var children: [SerializedNode]?"] : []),
    ...fields.map(({ name, property }) => `  public var ${name}: ${property}`),
    "  public var unknownFields: [String: JSONValue]",
    "",
    "  public init(json: JSONValue) throws {",
    "    var fields = try NodeFields(reading: json, as: Self.type)",
    ...(node.children ? ["    children = fields.takeChildren()"] : []),
    ...fields.map(
      ({ key, name, accessor }) =>
        `    ${name} = fields.take${accessor}(${swiftString(key)}, Schema.${name})`,
    ),
    "    unknownFields = fields.rest",
    "  }",
    "",
    "  public var json: JSONValue {",
    "    var fields = NodeFields(writing: Self.type, over: unknownFields)",
    ...(node.children ? ["    fields.putChildren(children)"] : []),
    ...fields.map(
      ({ key, name, accessor }) =>
        `    fields.put${accessor}(${swiftString(key)}, ${name}, Schema.${name})`,
    ),
    "    return fields.json",
    "  }",
    ...(fields.length > 0
      ? [
          "",
          "  private enum Schema {",
          ...fields.map(
            ({ name, schemaType, schema }) =>
              `    static let ${name}: FieldSchema<${schemaType}> = ${schema}`,
          ),
          "  }",
        ]
      : []),
    "}",
    "",
  ];
}

/**
 * A field's Swift value type, whether JSON `null` is among its values, and
 * the `FieldSchema` expression that reads it.
 */
function swiftField(
  type: FieldType,
  enums: Map<string, string>,
  where: string,
): { value: string; nullable: boolean; schema: string } {
  switch (type.kind) {
    case "string":
      return {
        value: "String",
        nullable: false,
        schema: `.string(default: ${literal(defaultOf(type, where), type, enums, where)})`,
      };
    case "boolean":
      return {
        value: "Bool",
        nullable: false,
        schema: `.boolean(default: ${literal(defaultOf(type, where), type, enums, where)})`,
      };
    case "number": {
      const options = [
        `default: ${literal(defaultOf(type, where), type, enums, where)}`,
        ...(type.min === undefined ? [] : [`min: ${type.min}`]),
        ...(type.max === undefined ? [] : [`max: ${type.max}`]),
        ...(type.clamp ? ["clamp: true"] : []),
      ].join(", ");
      return type.integer
        ? { value: "Int", nullable: false, schema: `.integer(${options})` }
        : { value: "Double", nullable: false, schema: `.number(${options})` };
    }
    case "enum": {
      const name = enumName(type, enums, where);
      const fallback =
        type.default === undefined
          ? "nil"
          : type.default === null
            ? `${name}?.none`
            : literal(type.default, type, enums, where);
      return {
        value: name,
        nullable: type.values.includes(null),
        schema: `.enumeration(default: ${fallback})`,
      };
    }
    case "nullable": {
      const inner = swiftField(type.inner, enums, where);
      if (inner.nullable) {
        throw new Error(`${where}: a nullable field can't hold null twice`);
      }
      return {
        value: inner.value,
        nullable: true,
        schema: `.nullable(${inner.schema}${type.defaultAsNull ? ", defaultAsNull: true" : ""})`,
      };
    }
    case "optional": {
      const inner = swiftField(type.inner, enums, where);
      return {
        ...inner,
        schema: `.optional(${inner.schema}${type.omitDefault ? ", omitDefault: true" : ""})`,
      };
    }
    case "aliased": {
      const inner = swiftField(type.inner, enums, where);
      const aliases = Object.entries(type.aliases)
        .sort(([a], [b]) => byCodeUnits(a, b))
        .map(
          ([alias, value]) =>
            `${swiftString(alias)}: ${literal(value, type.inner, enums, where)}`,
        )
        .join(", ");
      return { ...inner, schema: `.aliased(${inner.schema}, [${aliases}])` };
    }
    case "array": {
      if (readsAsAbsent(type.item)) {
        throw new Error(`${where}: an array item can't read as absent`);
      }
      const item = swiftField(type.item, enums, where);
      return {
        value: `[${item.value}${item.nullable ? "?" : ""}]`,
        nullable: false,
        schema: `.array(${item.schema})`,
      };
    }
    default:
      throw new Error(`${where}: codegen doesn't type ${type.kind} fields yet`);
  }
}

/** The type a wrapping field type reads its value through. */
function innerType(type: FieldType): FieldType | undefined {
  switch (type.kind) {
    case "nullable":
    case "optional":
    case "aliased":
    case "transform":
      return type.inner;
    default:
      return undefined;
  }
}

function readsAsAbsent(type: FieldType): boolean {
  if (type.kind === "optional" || type.kind === "raw") return true;
  if (type.kind === "enum") return type.default === undefined;
  const inner = innerType(type);
  return inner !== undefined && readsAsAbsent(inner);
}

/** A JSON value as a Swift literal of `type`'s value type. */
function literal(
  value: unknown,
  type: FieldType,
  enums: Map<string, string>,
  where: string,
): string {
  switch (type.kind) {
    case "string":
      return swiftString(value as string);
    case "boolean":
    case "number":
      return String(value);
    case "enum":
      return value === null
        ? "nil"
        : `${enumName(type, enums, where)}.${caseName(value as string)}`;
    case "nullable":
      return value === null ? "nil" : literal(value, type.inner, enums, where);
    case "optional":
    case "aliased":
      return literal(value, type.inner, enums, where);
    case "array":
      return `[${(value as unknown[]).map((item) => literal(item, type.item, enums, where)).join(", ")}]`;
    default:
      throw new Error(`${where}: no Swift literal for a ${type.kind} value`);
  }
}

function defaultOf(type: FieldType, where: string) {
  if (type.default === undefined) throw new Error(`${where} has no default`);
  return type.default;
}

/** Every enum's Swift name, by its signature. */
function enumNames(nodes: NodeDescription[]): Map<string, string> {
  const bySignature = new Map<string, Set<string>>();
  const visit = (type: FieldType, field: string): void => {
    if (type.kind === "enum") {
      const signature = enumSignature(type.values);
      bySignature.set(
        signature,
        (bySignature.get(signature) ?? new Set()).add(field),
      );
      return;
    }
    const inner = type.kind === "array" ? type.item : innerType(type);
    if (inner) visit(inner, field);
  };
  for (const node of nodes) {
    for (const [field, type] of Object.entries(node.fields)) visit(type, field);
    for (const [field, state] of Object.entries(node.state)) {
      visit(state.value, field);
    }
  }
  const names = new Map<string, string>();
  for (const [signature, fields] of bySignature) {
    const named = ENUM_NAMES[signature];
    if (!named && fields.size > 1) {
      throw new Error(
        `The enum ${signature} is used by ${[...fields].join(", ")}; name it in ENUM_NAMES`,
      );
    }
    names.set(signature, named ?? pascalCase([...fields][0] ?? ""));
  }
  const taken = new Map<string, string>();
  for (const [signature, name] of names) {
    const other = taken.get(name);
    if (other !== undefined) {
      throw new Error(
        `The enums ${other} and ${signature} would both be ${name}; name them in ENUM_NAMES`,
      );
    }
    taken.set(name, signature);
  }
  return names;
}

function enumName(
  type: Extract<FieldType, { kind: "enum" }>,
  enums: Map<string, string>,
  where: string,
): string {
  const name = enums.get(enumSignature(type.values));
  if (!name) throw new Error(`${where}: an enum without a name`);
  return name;
}

/** An enum's identity: its non-null values, in order. */
function enumSignature(values: unknown[]): string {
  const members = values.filter((value) => value !== null);
  if (members.some((value) => typeof value !== "string")) {
    throw new Error(
      `Codegen only types enums of strings, not ${JSON.stringify(values)}`,
    );
  }
  return JSON.stringify(members);
}

function caseName(value: string): string {
  return value === "" ? "empty" : identifier(camelCase(value));
}

/** The class name without its `Node` suffix, e.g. `ListItem`. */
function className(node: NodeDescription): string {
  return node.className.replace(/Node$/, "");
}

function payloadName(node: NodeDescription): string {
  return `Serialized${className(node)}Node`;
}

function pascalCase(name: string): string {
  const camel = camelCase(name);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

function camelCase(name: string): string {
  return name.replace(/[^A-Za-z0-9]+(.)?/g, (_, next: string | undefined) =>
    (next ?? "").toUpperCase(),
  );
}

function identifier(name: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    throw new Error(`${JSON.stringify(name)} isn't a Swift identifier`);
  }
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

function swiftString(value: string): string {
  let escaped = "";
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0;
    escaped +=
      char === "\\" || char === '"'
        ? `\\${char}`
        : char === "\n"
          ? "\\n"
          : char === "\r"
            ? "\\r"
            : char === "\t"
              ? "\\t"
              : code < 0x20
                ? `\\u{${code.toString(16)}}`
                : char;
  }
  return `"${escaped}"`;
}
